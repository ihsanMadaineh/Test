document.addEventListener('DOMContentLoaded', () => {
  const htmlElement = document.documentElement;
  const langToggle = document.getElementById('lang-toggle');
  const billingSwitch = document.getElementById('billing-switch');
  const priceElements = document.querySelectorAll('.price');

  let currentLang = localStorage.getItem('ufug-lang') || 'ar';

  function updatePrices() {
    const isYearly = billingSwitch.checked;
    const dict = translations[currentLang];
    priceElements.forEach((priceEl) => {
      const monthly = priceEl.getAttribute('data-monthly');
      const yearly = priceEl.getAttribute('data-yearly');
      if (monthly === '0') {
        priceEl.textContent = dict.plan1Price;
        return;
      }
      const value = isYearly ? yearly : monthly;
      priceEl.innerHTML = `${value}$ <span>${dict.perMonth}</span>`;
    });
  }

  function applyLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('ufug-lang', lang);
    htmlElement.setAttribute('lang', lang);
    htmlElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
    langToggle.textContent = lang === 'ar' ? 'EN' : 'عربي';

    const dict = translations[lang];
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (dict[key] && typeof dict[key] === 'string') {
        el.textContent = dict[key];
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        el.setAttribute('placeholder', dict[key]);
      }
    });

    updatePrices();
  }

  applyLanguage(currentLang);

  langToggle.addEventListener('click', () => {
    applyLanguage(currentLang === 'ar' ? 'en' : 'ar');
  });

  // تبديل الوضع الليلي وحفظ التفضيل
  const themeToggle = document.getElementById('theme-toggle');
  const savedTheme = localStorage.getItem('ufug-theme');

  if (savedTheme === 'dark') {
    htmlElement.setAttribute('data-theme', 'dark');
    themeToggle.textContent = '☀️';
  }

  themeToggle.addEventListener('click', () => {
    const isDark = htmlElement.getAttribute('data-theme') === 'dark';
    if (isDark) {
      htmlElement.removeAttribute('data-theme');
      themeToggle.textContent = '🌙';
      localStorage.setItem('ufug-theme', 'light');
    } else {
      htmlElement.setAttribute('data-theme', 'dark');
      themeToggle.textContent = '☀️';
      localStorage.setItem('ufug-theme', 'dark');
    }
  });

  // قائمة الجوال المتجاوبة
  const mobileMenuBtn = document.getElementById('mobile-menu-btn');
  const navLinks = document.getElementById('nav-links');

  mobileMenuBtn.addEventListener('click', () => {
    navLinks.classList.toggle('open');
  });

  navLinks.querySelectorAll('a').forEach((link) => {
    link.addEventListener('click', () => navLinks.classList.remove('open'));
  });

  // عداد الإحصائيات المتحرك
  const statNumbers = document.querySelectorAll('.stat-number');
  statNumbers.forEach((el) => {
    const target = Number(el.getAttribute('data-target'));
    let current = 0;
    const step = Math.max(1, Math.ceil(target / 40));
    const timer = setInterval(() => {
      current += step;
      if (current >= target) {
        el.textContent = target.toLocaleString('en-US');
        clearInterval(timer);
      } else {
        el.textContent = current.toLocaleString('en-US');
      }
    }, 30);
  });

  // تبديل الفوترة الشهرية والسنوية
  billingSwitch.addEventListener('change', updatePrices);

  // الأسئلة الشائعة التفاعلية
  const faqItems = document.querySelectorAll('.faq-item');
  faqItems.forEach((item) => {
    const question = item.querySelector('.faq-question');
    question.addEventListener('click', () => {
      faqItems.forEach((other) => {
        if (other !== item) other.classList.remove('active');
      });
      item.classList.toggle('active');
    });
  });

  // نموذج الاشتراك التفاعلي
  const signupForm = document.getElementById('signup-form');
  const feedbackMsg = document.getElementById('form-feedback');

  signupForm.addEventListener('submit', (e) => {
    e.preventDefault();
    const nameInput = document.getElementById('user-name');
    const emailInput = document.getElementById('user-email');
    feedbackMsg.textContent = translations[currentLang].formSuccess(nameInput.value, emailInput.value);
    signupForm.reset();
  });

  // زر العودة للأعلى
  const scrollTopBtn = document.getElementById('scroll-top');
  window.addEventListener('scroll', () => {
    if (window.scrollY > 350) {
      scrollTopBtn.classList.add('visible');
    } else {
      scrollTopBtn.classList.remove('visible');
    }
  });

  scrollTopBtn.addEventListener('click', () => {
    window.scrollTo({ top: 0, behavior: 'smooth' });
  });
});